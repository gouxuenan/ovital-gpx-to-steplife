'use strict';
const assert = require('node:assert/strict');
const C = require('../converter.js');
const point = (lon, lat) => ({lon, lat, lonText:String(lon), latText:String(lat), altitude:0});
const track = {segments:[[point(0,0),point(0,1),point(0,2)]]};
const start = C.startTimestamp('2019-11-30T08:00:00');
assert.equal(start, Date.parse('2019-11-30T00:00:00Z')/1000);
assert.throws(()=>C.startTimestamp('2019-02-30T08:00'));
const result = C.convert(track,start,2.5);
const rows = result.csv.replace(/^\ufeff/,'').trim().split('\r\n');
assert.equal(rows[0],C.HEADER);
assert.equal(rows.length,4);
assert.ok(rows.every(row=>row.split(',').length===11));
assert.deepEqual(rows.slice(1).map(row=>Number(row.split(',')[0])),[start,start+3,start+5]);
assert.equal(result.duration,5);
assert.ok(Math.abs(result.total-222389.85328911748)<0.00001);
assert.equal(C.convert({segments:[[point(0,0)],[point(0,2)]]},start,10).total,0);
assert.equal(C.convert({segments:[[point(0,0)]]},start,10).duration,0);
assert.throws(()=>C.convert(track,start,0));
assert.throws(()=>C.convert(track,start,NaN));
assert.equal(C.filename('sample.csv'),'sample.csv');
assert.throws(()=>C.filename('CON'));
assert.throws(()=>C.filename('../sample'));
const many = {segments:[Array.from({length:145},()=>point(0,0))]};
assert.equal(C.convert(many,start,36000/144).end,start+36000);
console.log('PASS: header, UTC+8, timestamps, fractional rounding, distance, segments, validation and endpoint.');
